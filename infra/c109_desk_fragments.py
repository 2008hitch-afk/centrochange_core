"""Build static Desk fragments from the canonical website templates.

The Desk must not fetch/render a website page at runtime. This generator shares
the existing presentation markup while the native-first workflows are verified.
It never copies sidebar, scripts, CSRF values or demo-only Jinja conditions.
"""

import json
from html.parser import HTMLParser
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app/centrochange_core/centrochange_core/www"
TARGET = ROOT / "app/centrochange_core/centrochange_core/public/js/cc_desk_fragments.js"
PAGES = {
    "agenda": "centrochange",
    "finance": "finanza",
    "professional": "professionista",
    "patient": "pazienti_report",
}
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}


class Elements(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=False)
        self.source = source
        self.lines = [0]
        for match in re.finditer("\n", source):
            self.lines.append(match.end())
        self.stack = []
        self.found = {}
        self.feed(source)

    def source_offset(self):
        line, column = self.getpos()
        return self.lines[line - 1] + column

    def handle_starttag(self, tag, attrs):
        if tag in VOID:
            return
        properties = dict(attrs)
        wanted = "page-wrapper" in (properties.get("class") or "").split() or properties.get("id") == "modal"
        self.stack.append((tag, self.source_offset(), "page" if "page-wrapper" in (properties.get("class") or "").split() else "modal" if wanted else None))

    def handle_endtag(self, tag):
        if not self.stack or self.stack[-1][0] != tag:
            raise ValueError(f"unbalanced HTML: {tag}")
        _, start, key = self.stack.pop()
        if key:
            if key in self.found:
                raise ValueError(f"duplicate {key}")
            self.found[key] = self.source[start : self.source_offset() + len(f"</{tag}>")]


def fragment(source):
    body = re.search(r'<body\s+class="([^"]+)"', source)
    if not body:
        raise ValueError("body class missing")
    elements = Elements(source).found
    if "page" not in elements:
        raise ValueError("page wrapper missing")
    page = re.sub(r"{% if uat_demo %}.*?{% endif %}", "", elements["page"], flags=re.S)
    modal = elements.get("modal", "")
    if "{%" in page or "{{" in page or "{%" in modal:
        raise ValueError("template directive in Desk fragment")
    if 'id="cc-main"' not in page:
        raise ValueError("required controller anchors missing")
    return {"bodyClass": body.group(1), "page": page, "modal": modal}


def generate():
    fragments = {key: fragment((SOURCE / f"{name}.html").read_text()) for key, name in PAGES.items()}
    return "// Generated by infra/c109_desk_fragments.py; edit canonical www templates.\n" + \
        "export const deskFragments = " + json.dumps(fragments, ensure_ascii=False, separators=(",", ":")) + ";\n"


if __name__ == "__main__":
    TARGET.write_text(generate())
